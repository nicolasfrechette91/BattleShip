"""M7t synthetic readout test (docs/rl_m7t_synthetic_prerequisite_review_2026-09-29.md, section 4, as revised by the user).

Zero optimizer steps. No BattleShip, no native tick, no new network: the saved T networks of the registered
prerequisite run (logs/m7t_synth_prereq/s{0,1,2}_T.pt) are only evaluated. The harness rl/tools/m7t_synthetic_prereq.py
is imported unchanged (world, data, observation builder, networks); the registered FAIL is not touched.

    python rl/tools/m7t_synthetic_readout.py pin --out DIR     # writes DIR/protocol.json (write-once) with its hash
    python rl/tools/m7t_synthetic_readout.py run --out DIR     # refuses unless DIR/protocol.json matches PROTOCOL

One controlled change: the goal distance used by the greedy rule, from the goal node d(T(z, a), w(G)) (original readout,
"O") to min over at most 32 representative full states g_i of cell G of d(T(z, a), z(g_i)) ("R"). Representatives come
only from the frozen training archive (training-split rows of the registered data), in a fixed hash order; evaluation
trajectories are never used. Action set, tie-breaking (torch.argmin, lowest index), start, goals, horizon and batching
are unchanged. The original readout must reproduce the saved registered episodes word for word before R is evaluated.
"""
